"""System prompt builder for the PassportCard Pay voice agent.

Design goals:
- Per-call prompts are small and focused — only the knowledge needed for the
  one randomly-selected case is in the system prompt.
- The agent has enough domain context per scenario to answer the obvious
  follow-up questions confidently and *without inventing* specifics
  (amounts, dates, addresses).
- Voice-only rules (Hebrew, plural address, no URL reading, "מסביב לשעון"
  instead of "24/7", short sentences with pauses) live in one tight block.

The category table maps RC + failure_reason → a stable category key with
its own knowledge block. Adding a new case = either fitting it into an
existing category or appending a new one here.
"""


# ---- Category classifier ----

def _category(case: dict) -> str:
    rc = (case.get("rc") or "").strip()
    reason = (case.get("failure_reason") or "").lower()

    if "stolen" in reason:
        return "card_stolen"
    if "black list" in reason or "blacklist" in reason:
        return "blacklist"
    if "credit guard" in reason or "credit company" in reason:
        if "no communication" in reason or "no response" in reason:
            return "platform_communication"
        return "credit_company_refusal"
    if "pfs failure" in reason or "mpe failure" in reason:
        return "platform_communication"
    if "card not activated" in reason:
        return "card_not_activated"
    if "no claim mcc" in reason or "mcc insurance" in reason:
        return "mcc_insurance"
    if "didn't sign" in reason or "fx agreement" in reason:
        return "fx_agreement_not_signed"
    if "atm" in reason:
        if "daily" in reason:
            return "atm_limit_daily"
        if "travel" in reason:
            return "atm_limit_travel"
        return "atm_limit_generic"
    if "yearly" in reason:
        return "usage_limit_yearly"
    if "six month" in reason:
        return "usage_limit_six_month"
    if "blocked country" in reason:
        return "blocked_country"
    if "mcc usage limit" in reason or "risk country" in reason:
        return "risk_mcc_limit"
    return "generic"


