def _format_faq(faq: list[tuple[str, str]]) -> str:
    if not faq:
        return ""
    lines = ["שאלות נפוצות שעלולות לעלות בשיחה ואיך לענות עליהן:"]
    for q, a in faq:
        lines.append(f"- שואלים: \"{q}\"")
        lines.append(f"  עונים בעברית טבעית: {a}")
    return "\n".join(lines)


def build_instructions(customer_name: str, case: dict) -> str:
    """Build a focused system prompt for the selected case only."""
